const MONTH_INDEX: Record<string, number> = {
  Jan: 1,
  Feb: 2,
  Mar: 3,
  Apr: 4,
  May: 5,
  Jun: 6,
  Jul: 7,
  Aug: 8,
  Sep: 9,
  Oct: 10,
  Nov: 11,
  Dec: 12,
};

export function parseCertDateKey(issueDate: string): number {
  const [mon, yr] = issueDate.trim().split(/\s+/);
  const yearNum = parseInt(yr || '0', 10);
  const monthNum = MONTH_INDEX[mon] || 0;
  return yearNum * 100 + monthNum;
}

